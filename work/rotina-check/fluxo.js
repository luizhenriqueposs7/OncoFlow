async (page) => {
  const base = 'http://127.0.0.1:3105';
  const result = {}; let stage = 'Meu dia';
  try {
    await page.request.post(`${base}/api/demo/reset`);
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.goto(base);
    await page.getByRole('heading', { name: 'Meu dia', exact: true }).waitFor();
    await page.getByRole('button', { name: 'Nova tarefa', exact: true }).click();
    await page.getByRole('combobox', { name: 'Paciente', exact: true }).selectOption('pac-maria');
    await page.getByLabel('Título da tarefa', { exact: true }).fill('Organizar transporte fictício');
    await page.getByLabel('Motivo ou orientação para a equipe', { exact: true }).fill('Verificar disponibilidade na demonstração.');
    await page.getByRole('button', { name: 'Criar tarefa', exact: true }).click();
    await page.getByRole('dialog').waitFor({ state: 'detached' });
    await page.getByRole('heading', { name: 'Organizar transporte fictício', exact: true }).waitFor();
    result.taskCreated = true;
    stage = 'filtros';
    await page.getByRole('button', { name: 'Minhas tarefas', exact: true }).click();
    if (!(await page.getByRole('heading', { name: 'Organizar transporte fictício', exact: true }).isVisible())) throw new Error('Assigned task missing');
    await page.reload();
    await page.getByRole('button', { name: 'Minhas tarefas', exact: true }).waitFor();
    if (new URL(page.url()).searchParams.get('fila') !== 'minhas') throw new Error('Filter URL lost');
    await page.getByRole('button', { name: 'Vencidas', exact: true }).click();
    if (await page.getByRole('heading', { name: 'Organizar transporte fictício', exact: true }).count()) throw new Error('Future task in overdue filter');
    await page.getByRole('button', { name: 'Abrir paciente', exact: true }).first().click();
    await page.getByRole('heading', { name: 'José Pereira da Silva', exact: true }).waitFor();
    if (new URL(page.url()).searchParams.get('paciente') !== 'pac-001') throw new Error('Wrong patient');
    await page.getByRole('tab', { name: 'Histórico', exact: true }).click();
    await page.getByRole('region', { name: 'Histórico do paciente', exact: true }).waitFor();
    result.filtersAndPatientContext = true;
    stage = 'resposta vinculada';
    await page.locator('nav:visible').getByRole('button', { name: /Pendências/ }).click();
    await page.getByRole('button', { name: 'Todas', exact: true }).click();
    const pedido = page.locator('.review-item').filter({ hasText: 'Renato Oliveira Santos' });
    await pedido.getByRole('button', { name: 'Responder à solicitação', exact: true }).click();
    await page.getByRole('textbox', { name: 'Mensagem para Renato Oliveira Santos', exact: true }).fill('Resposta fictícia vinculada ao pedido.');
    await page.getByRole('button', { name: 'Enviar mensagem', exact: true }).click();
    await page.getByText('Resposta fictícia vinculada ao pedido.', { exact: true }).waitFor();
    const pro = await (await page.request.get(`${base}/api/pro/estado`, { headers: { 'x-demo-usuario': 'usr-camila' } })).json();
    const msg = pro.pacientes.find(p => p.nome === 'Renato Oliveira Santos').mensagens.find(m => m.texto === 'Resposta fictícia vinculada ao pedido.');
    if (msg.pendenciaId !== new URL(page.url()).searchParams.get('solicitacao')) throw new Error('Reply link not stored');
    result.linkedReply = true;
    stage = 'lembrete';
    await page.goto(`${base}/paciente?tela=agenda`);
    const exame = page.locator('article').filter({ hasText: 'Exames de sangue pré-tratamento' });
    await exame.getByRole('button', { name: 'Criar lembrete', exact: true }).click();
    await page.getByRole('radio', { name: 'Duas horas antes', exact: true }).check();
    await page.getByRole('button', { name: 'Confirmar lembrete', exact: true }).click();
    await page.getByRole('dialog').waitFor({ state: 'detached' });
    await exame.getByRole('button', { name: 'Lembrete criado', exact: true }).waitFor();
    await page.reload();
    await page.getByRole('heading', { name: 'Minha agenda', exact: true }).waitFor();
    result.reminderAndReload = true;
    stage = 'documento e histórico do navegador';
    await page.goto(`${base}/paciente?tela=documentos`);
    await page.getByRole('button', { name: /Resultado do hemograma/ }).click();
    await page.reload();
    await page.getByRole('heading', { name: 'Resultado do hemograma', exact: true }).waitFor();
    await page.goBack();
    await page.getByRole('heading', { name: 'Meus documentos', exact: true }).waitFor();
    result.documentUrlAndBack = true;
    stage = 'Lia resposta completa';
    await page.goto(`${base}/paciente?tela=lia`);
    await page.getByRole('button', { name: 'Prefiro digitar', exact: true }).click();
    await page.getByRole('textbox', { name: /Mensagem para a Lia/ }).fill('Quando é minha próxima consulta?');
    await page.getByRole('button', { name: 'Enviar', exact: true }).click();
    await page.getByRole('button', { name: 'Sim, por favor', exact: true }).waitFor();
    await page.getByRole('button', { name: 'Falar com a Lia', exact: true }).click();
    const resposta = await page.locator('.lia-spoken-response').textContent();
    if (!resposta.includes('Sua próxima consulta é') || !resposta.includes('Quer que eu te lembre')) throw new Error('Partial voice response');
    result.completeVoiceResponse = true;
    await page.getByRole('button', { name: 'Agora não', exact: true }).click();
    await page.getByRole('button', { name: 'Voltar', exact: true }).click();
    stage = 'diálogo';
    await page.getByRole('button', { name: 'Preferências de leitura e voz', exact: true }).click();
    if (!(await page.evaluate(() => !!document.activeElement.closest('dialog')))) throw new Error('Focus outside dialog');
    await page.keyboard.press('Escape');
    if (await page.getByRole('dialog').count()) throw new Error('Escape did not close dialog');
    result.keyboardDialog = true;
    return result;
  } catch (error) { throw new Error(`${stage}: ${error.message}`); }
}
